#!/usr/bin/env python3
"""Generate the browser-side manifest for complete demo-auto image triplets."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEMOS = ROOT / "assets" / "demos"
METADATA = DEMOS / "demo-auto-metadata.json"
OUTPUT = DEMOS / "auto-demos.js"


def load_metadata() -> dict[str, dict[str, object]]:
    if not METADATA.exists():
        return {}
    value = json.loads(METADATA.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError("demo-auto-metadata.json must contain an object")
    return value


def main() -> int:
    metadata = load_metadata()
    demos: list[dict[str, object]] = []
    for source in sorted(DEMOS.glob("demo-auto-*.png")):
        if source.name.endswith(("-background.png", "-foreground.png", "-thumb.png")):
            continue
        slug = source.stem.removeprefix("demo-auto-")
        foreground = DEMOS / f"demo-auto-{slug}-foreground.png"
        background = DEMOS / f"demo-auto-{slug}-background.png"
        if not foreground.is_file() or not background.is_file():
            continue
        thumb = DEMOS / f"demo-auto-{slug}-thumb.png"
        defaults: dict[str, object] = {
            "slug": slug,
            "src": f"assets/demos/{source.name}",
            "background": f"assets/demos/{background.name}",
            "foreground": f"assets/demos/{foreground.name}",
            "thumb": f"assets/demos/{thumb.name if thumb.is_file() else source.name}",
            "label": slug.replace("-", " ").title(),
            "centerX": "0.50",
            "centerY": "0.47",
            "radius": "0.43",
            "strength": "0.70",
            "rigType": "human",
            "chestMotion": True,
        }
        override = metadata.get(slug, {})
        if not isinstance(override, dict):
            raise ValueError(f"metadata for {slug!r} must be an object")
        defaults.update(override)
        demos.append(defaults)

    payload = json.dumps(demos, ensure_ascii=False, separators=(",", ":"))
    OUTPUT.write_text(
        "// Generated by scripts/build_demo_manifest.py; do not edit.\n"
        f"window.P3D_AUTO_DEMOS={payload};\n",
        encoding="utf-8",
    )
    print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(demos)} demos)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
